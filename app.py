# ==========================================
# STREAMLIT DASHBOARD (app.py)
# ==========================================
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

# 1. Page Configuration
# This sets the browser tab title and stretches the layout across the screen
st.set_page_config(page_title="Afficionado Demand Forecaster", layout="wide")

# 2. Data Loading Function
# The @st.cache_data decorator ensures the app doesn't reload the CSVs every time the user clicks a button
@st.cache_data
def load_data():
    # Load the CSVs generated by our Jupyter Notebook models
    daily = pd.read_csv('daily_forecasts.csv', parse_dates=['ds'])
    hourly = pd.read_csv('hourly_predictions.csv', parse_dates=['transaction_date'])
    return daily, hourly

daily_forecast_df, hourly_pred_df = load_data()

# 3. Dashboard Header
st.title("☕ Afficionado Coffee Roasters: Predictive Demand Analytics")
st.markdown("Transforming historical sales data into proactive scheduling and inventory intelligence.")

# 4. Sidebar Controls (User Inputs)
st.sidebar.header("Control Panel")
# Create a dropdown menu using the unique store IDs from our data
selected_store = st.sidebar.selectbox("Select Store ID", daily_forecast_df['store_id'].unique())
# Create a slider to let the user choose how far into the future to look (7 to 30 days)
horizon = st.sidebar.slider("Forecast Horizon (Days)", min_value=7, max_value=30, value=14)

# 5. Filter the Data based on User Selection
store_daily = daily_forecast_df[daily_forecast_df['store_id'] == selected_store].tail(horizon)
store_hourly = hourly_pred_df[hourly_pred_df['store_id'] == selected_store]

# 6. Layout: Split the screen into two equal columns
col1, col2 = st.columns(2)

# ==========================================
# LEFT COLUMN: PROPHET REVENUE FORECAST
# ==========================================
with col1:
    st.subheader("Medium-Term: Daily Revenue Forecast")
    
    # Build a Plotly line chart with confidence intervals
    fig1 = go.Figure()
    # Add the main prediction line (yhat)
    fig1.add_trace(go.Scatter(x=store_daily['ds'], y=store_daily['yhat'], 
                              name='Forecast', line=dict(color='blue')))
    # Add the upper and lower bounds of the confidence interval
    fig1.add_trace(go.Scatter(x=store_daily['ds'], y=store_daily['yhat_upper'], 
                              fill=None, mode='lines', line_color='rgba(0,0,255,0)', showlegend=False))
    fig1.add_trace(go.Scatter(x=store_daily['ds'], y=store_daily['yhat_lower'], 
                              fill='tonexty', mode='lines', line_color='rgba(0,100,255,0.2)', name='Confidence Interval'))
    
    fig1.update_layout(xaxis_title="Date", yaxis_title="Projected Revenue ($)", hovermode="x unified")
    # Render the chart in Streamlit
    st.plotly_chart(fig1, use_container_width=True)

# ==========================================
# RIGHT COLUMN: XGBOOST PEAK DEMAND
# ==========================================
with col2:
    st.subheader("Short-Term: Peak Demand Heatmap")
    
    # Group the hourly predictions to find the average expected demand for each hour and day
    heatmap_data = store_hourly.groupby(['day_of_week', 'hour'])['predicted_qty'].mean().reset_index()
    # Pivot the data into a grid format suitable for a heatmap
    heatmap_pivot = heatmap_data.pivot(index='hour', columns='day_of_week', values='predicted_qty')
    
    # Define day names for the X-axis instead of numbers 0-6
    day_names = {0: 'Mon', 1: 'Tue', 2: 'Wed', 3: 'Thu', 4: 'Fri', 5: 'Sat', 6: 'Sun'}
    heatmap_pivot.rename(columns=day_names, inplace=True)
    
    # Build a Plotly Heatmap
    fig2 = px.imshow(heatmap_pivot, 
                     labels=dict(x="Day of Week", y="Hour of Day", color="Demand (Cups)"),
                     color_continuous_scale="YlOrRd",
                     aspect="auto")
    
    fig2.update_layout(yaxis=dict(tickmode='linear', tick0=0, dtick=1))
    # Render the chart in Streamlit
    st.plotly_chart(fig2, use_container_width=True)

# 7. Business Impact Footer
st.markdown("---")
st.markdown("### 📊 Operational Insights")
st.write("""
- **Staff Scheduling:** Utilize the Heatmap to identify rush hours 24-48 hours in advance, ensuring optimal barista staffing.
- **Inventory Waste Reduction:** Align perishable orders (milk, pastries) with the Daily Revenue Forecast to minimize over-ordering.
""")